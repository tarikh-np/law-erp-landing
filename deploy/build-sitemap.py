#!/usr/bin/env python3
"""Generate sitemap.xml from the pages in the repo.

Only indexable canonical URLs on the new origin are listed, with an accurate
lastmod taken from git. No changefreq, no priority, no hreflang, no image entries
and no 404.html — the sitemap lists pages, nothing else.

    python deploy/build-sitemap.py [--check]

--check regenerates in memory and exits non-zero if sitemap.xml differs.
"""
from __future__ import annotations

import datetime as dt
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORIGIN = 'https://www.tarikh.tech'
EXCLUDE = {'404.html'}
TRAILING_SLASH_DIRS = {'blog'}


def rel(p: pathlib.Path) -> str:
    return p.relative_to(ROOT).as_posix()


def route_for(p: pathlib.Path) -> str:
    r = rel(p)
    if r == 'index.html':
        return '/'
    if r.endswith('/index.html'):
        d = r[: -len('/index.html')]
        return '/' + d + ('/' if d in TRAILING_SLASH_DIRS else '')
    return '/' + r


def lastmod(p: pathlib.Path) -> str:
    """Last commit date for the file, or today if the working copy has moved on."""
    r = rel(p)
    try:
        dirty = subprocess.run(['git', 'diff', '--quiet', 'HEAD', '--', r],
                               cwd=ROOT).returncode != 0
        untracked = subprocess.run(['git', 'ls-files', '--error-unmatch', r],
                                   cwd=ROOT, capture_output=True).returncode != 0
        out = subprocess.run(['git', 'log', '-1', '--format=%cI', '--', r],
                             cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except OSError:
        dirty, untracked, out = False, True, ''
    if dirty or untracked or not out:
        return dt.date.today().isoformat()
    return out[:10]


def build() -> str:
    pages = sorted(p for p in ROOT.rglob('*.html')
                   if '.git' not in p.parts and 'node_modules' not in p.parts)
    entries = []
    for p in pages:
        if p.name in EXCLUDE:
            continue
        route = route_for(p)
        loc = f'{ORIGIN}/' if route == '/' else f'{ORIGIN}{route}'
        entries.append((loc, lastmod(p)))
    entries.sort(key=lambda e: (e[0] != f'{ORIGIN}/', e[0]))

    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- Tarikh sitemap. Canonical URLs on https://www.tarikh.tech only.',
             '     Generated by deploy/build-sitemap.py — do not hand-edit. -->',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for loc, lm in entries:
        lines += ['  <url>',
                  f'    <loc>{loc}</loc>',
                  f'    <lastmod>{lm}</lastmod>',
                  '  </url>']
    lines += ['</urlset>', '']
    return '\n'.join(lines)


def main() -> int:
    xml = build()
    target = ROOT / 'sitemap.xml'
    if '--check' in sys.argv:
        current = target.read_text(encoding='utf-8') if target.exists() else ''
        if current.replace('\r\n', '\n') != xml:
            print('sitemap.xml is out of date — run python deploy/build-sitemap.py')
            return 1
        print('sitemap.xml is up to date')
        return 0
    target.write_text(xml, encoding='utf-8', newline='\n')
    print(f'wrote sitemap.xml ({xml.count("<loc>")} urls)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
