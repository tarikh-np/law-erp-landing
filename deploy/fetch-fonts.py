#!/usr/bin/env python3
"""Self-host the webfonts so the site never calls fonts.googleapis.com.

    python deploy/fetch-fonts.py

Downloads the latin and latin-ext subsets of Inter (variable 400-700) and
Newsreader (variable 500-600 + italic 500) exactly as Google Fonts serves them,
writes assets/fonts/*.woff2 and regenerates css/fonts.css with local paths.

Run it again only if a family, weight or subset changes -- the output files are
committed, so a normal clone needs nothing.
"""
from __future__ import annotations

import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / 'assets' / 'fonts'
CSS_OUT = ROOT / 'css' / 'fonts.css'

UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/125.0.0.0 Safari/537.36')
CSS_URL = ('https://fonts.googleapis.com/css2'
           '?family=Inter:wght@400..700'
           '&family=Newsreader:ital,opsz,wght@0,6..72,500..600;1,6..72,500'
           '&display=swap')
# Devanagari text falls back to a system font, as it does today: neither family
# ships a Devanagari subset. Only the subsets the site actually renders are kept.
KEEP = ('latin', 'latin-ext')

HEADER = """/* Self-hosted webfonts. Generated by deploy/fetch-fonts.py -- do not edit.
   Inter and Newsreader, latin and latin-ext subsets, OFL-1.1.
   font-display: swap; the preload in each page's <head> covers the body weight. */
"""


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def slug(family: str, style: str, subset: str) -> str:
    name = family.lower().replace(' ', '-')
    if style == 'italic':
        name += '-italic'
    return f'{name}-{subset}'


def main() -> int:
    css = fetch(CSS_URL).decode('utf-8')
    blocks = re.findall(r'/\*\s*([a-z0-9-]+)\s*\*/\s*(@font-face\s*\{.*?\})',
                        css, re.S)
    if not blocks:
        sys.exit('no @font-face blocks in the Google Fonts response')

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    out: list[str] = [HEADER]
    written: list[tuple[str, int]] = []

    for subset, block in blocks:
        if subset not in KEEP:
            continue
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        style = re.search(r'font-style:\s*(\w+)', block).group(1)
        weight = re.search(r'font-weight:\s*([^;]+);', block).group(1).strip()
        remote = re.search(r'url\((https://[^)]+)\)', block).group(1)

        filename = slug(family, style, subset) + '.woff2'
        data = fetch(remote)
        (FONT_DIR / filename).write_bytes(data)
        written.append((filename, len(data)))

        out.append(
            '@font-face {\n'
            f"  font-family: '{family}';\n"
            f'  font-style: {style};\n'
            f'  font-weight: {weight};\n'
            '  font-display: swap;\n'
            f'  src: url(/assets/fonts/{filename}) format("woff2");\n'
            f'  unicode-range: {re.search(r"unicode-range:\s*([^;]+);", block).group(1).strip()};\n'
            '}\n'
        )

    CSS_OUT.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    for name, size in written:
        print(f'wrote assets/fonts/{name} ({size // 1024} KB)')
    print(f'wrote css/fonts.css ({CSS_OUT.stat().st_size} bytes)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
