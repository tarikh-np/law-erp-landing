#!/usr/bin/env python3
"""Bundle and minify the stylesheets. No framework, no node_modules.

    python deploy/minify.py            # write css/site.min.css
    python deploy/minify.py --check    # exit non-zero if the committed file is stale

Why CSS only: everything the minifier does is provably whitespace- and
comment-only, and the fingerprints below enforce that. JavaScript cannot be
treated the same way at this size (line comments and automatic semicolon
insertion make newline-stripping unsafe), and js/main.js is 5.6 KB, so it stays
as authored and is served compressed by the host.

The transform:
  * string literals are lifted out first, so `content`/`url()` values are byte-identical
  * `/* ... */` comments are removed
  * runs of whitespace collapse to one space, then the spaces around `{`, `}`, `;`
    and `,` are dropped. `:` and calc() operators are left alone.

`--check` re-runs the transform against the sources and compares, so a CSS edit
without a re-run fails `deploy/verify.py` instead of silently shipping stale CSS.
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

CSS_SOURCES = ('css/fonts.css', 'css/style.css', 'css/responsive.css')
CSS_OUT = 'css/site.min.css'

BANNER = '/* Tarikh — bundle of css/fonts.css, css/style.css and css/responsive.css.\n' \
         '   Generated by deploy/minify.py; edit the sources, then re-run it. */\n'

# CSS strings start right after `:`, `(` or `,` (or the start of the file). Requiring
# that prefix keeps an apostrophe inside a comment -- e.g. "each page's body weight"
# -- from being mistaken for a string and swallowing the rest of the stylesheet.
STRING_RE = re.compile(
    r'(?:(?<=[:(,])|^|\s)'
    '(?:"(?:\\\\.|[^"\\\\])*"|\'(?:\\\\.|[^\'\\\\])*\')'
    r'(?=[\s;},)]|$)'
)


def protect_strings(text: str) -> tuple[str, list[str]]:
    strings: list[str] = []

    def swap(m: re.Match) -> str:
        strings.append(m.group(0))
        return f'\x00{len(strings) - 1}\x00'

    return STRING_RE.sub(swap, text), strings


def restore_strings(text: str, strings: list[str]) -> str:
    return re.sub(r'\x00(\d+)\x00', lambda m: strings[int(m.group(1))], text)


def strip_comments(text: str) -> str:
    out: list[str] = []
    i, n = 0, len(text)
    while i < n:
        if text.startswith('/*', i):
            end = text.find('*/', i + 2)
            i = n if end == -1 else end + 2
            continue
        out.append(text[i])
        i += 1
    return ''.join(out)


def minify(text: str) -> str:
    protected, strings = protect_strings(text)
    protected = strip_comments(protected)
    protected = re.sub(r'\s+', ' ', protected)
    protected = re.sub(r'\s*([{};,])\s*', r'\1', protected)
    return restore_strings(protected.strip(), strings)


def fingerprint(text: str) -> str:
    """Everything that is not whitespace or a comment, with strings kept whole."""
    protected, strings = protect_strings(text)
    protected = re.sub(r'\s+', '', strip_comments(protected))
    return restore_strings(protected, strings)


def build() -> str:
    parts = []
    for rel in CSS_SOURCES:
        source = (ROOT / rel).read_text(encoding='utf-8')
        if fingerprint(source) != fingerprint(minify(source)):
            raise SystemExit(f'minifier changed more than whitespace in {rel}')
        parts.append(f'/* {rel} */\n{minify(source)}')
    return BANNER + '\n'.join(parts) + '\n'


def main() -> int:
    wanted = build()
    path = ROOT / CSS_OUT
    current = path.read_text(encoding='utf-8') if path.exists() else None
    if current == wanted:
        print(f'{CSS_OUT}: up to date ({len(wanted) // 1024} KB)')
        return 0
    if '--check' in sys.argv[1:]:
        print(f'STALE: {CSS_OUT} -- re-run python deploy/minify.py')
        return 1
    path.write_text(wanted, encoding='utf-8', newline='\n')
    print(f'{CSS_OUT}: written ({len(wanted) // 1024} KB, '
          f'from {sum((ROOT / r).stat().st_size for r in CSS_SOURCES) // 1024} KB of source)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
